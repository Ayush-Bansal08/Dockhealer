"""Run `docker build` safely and capture what happened.

Three design decisions, each defended in docs/LESSONS or in an interview:

1. STAGED CONTEXT. We never point Docker at the user's real project directory. Docker sends the
   whole directory to the daemon, so `COPY . .` would bake `.env`, `*.pem`, `.git` ... into the image.
   Instead we copy only the files the scanner approved into a temporary directory and build there.
   Side effects: the user's project is never modified, and what the validator checked (info.files)
   is exactly what Docker can see.

2. DOCKERFILE OUTSIDE THE CONTEXT. The generated Dockerfile is written to its own temp directory and
   passed with `-f`. Nothing generated by the model is ever written into the user's project.

3. BOUNDED EXECUTION. List-form arguments (no shell), a hard timeout, and a capped log. The only thing
   the model controls is the *content* of the Dockerfile, never the command that is run.

`runner` is injected so tests can simulate Docker without a daemon (dependency injection).
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
import time
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterator

from .scanner import ProjectInfo

DEFAULT_TIMEOUT_S = 600
LOG_TAIL_CHARS = 20_000          # the error is at the END of a build log, so keep the tail
MAX_CONTEXT_BYTES = 200 * 1024 * 1024


class DockerUnavailable(Exception):
    """The docker CLI is not installed / not on PATH."""


class ContextTooLarge(Exception):
    """Approved project files exceed MAX_CONTEXT_BYTES."""


@dataclass(frozen=True)
class BuildResult:
    success: bool
    returncode: int | None          # None when the build was killed by the timeout
    duration_s: float
    log: str                        # tail of combined stderr+stdout
    tag: str
    timed_out: bool = False
    image_size_bytes: int | None = None


def make_tag(info: ProjectInfo) -> str:
    name = re.sub(r"[^a-z0-9_.-]+", "-", Path(info.root).name.lower()).strip("-.") or "app"
    return f"dockhealer-{name}:{int(time.time())}"


@contextmanager
def staged_context(info: ProjectInfo) -> Iterator[Path]:
    """Copy ONLY scanner-approved files into a temp directory and yield its path."""
    src_root = Path(info.root)
    total = sum((src_root / rel).stat().st_size for rel in info.files if not os.path.islink(src_root / rel))
    if total > MAX_CONTEXT_BYTES:
        raise ContextTooLarge(f"project files total {total / 1e6:.0f} MB (limit {MAX_CONTEXT_BYTES / 1e6:.0f} MB)")
    with tempfile.TemporaryDirectory(prefix="dockhealer-ctx-") as tmp:
        ctx = Path(tmp) / "context"
        ctx.mkdir()
        for rel in info.files:
            src = src_root / rel
            if os.path.islink(src):  # re-check: a file could have been swapped for a symlink after the scan
                continue
            dst = ctx / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
        yield ctx


def _text(value: str | bytes | None) -> str:
    """TimeoutExpired carries bytes even when text=True was requested; normalise to str."""
    if value is None:
        return ""
    return value.decode("utf-8", "replace") if isinstance(value, bytes) else value


def _tail(log: str) -> str:
    return log if len(log) <= LOG_TAIL_CHARS else "[... log truncated ...]\n" + log[-LOG_TAIL_CHARS:]


def image_size(tag: str, runner: Callable = subprocess.run) -> int | None:
    try:
        p = runner(["docker", "image", "inspect", tag, "--format", "{{.Size}}"],
                   capture_output=True, text=True, timeout=30)
        return int(p.stdout.strip()) if p.returncode == 0 else None
    except (subprocess.TimeoutExpired, ValueError, OSError):
        return None


def remove_image(tag: str, runner: Callable = subprocess.run) -> bool:
    try:
        return runner(["docker", "rmi", "-f", tag], capture_output=True, text=True, timeout=60).returncode == 0
    except (subprocess.TimeoutExpired, OSError):
        return False


def run_build(info: ProjectInfo, dockerfile: str, *, tag: str | None = None,
              timeout_s: float = DEFAULT_TIMEOUT_S, runner: Callable = subprocess.run,
              clock: Callable[[], float] = time.monotonic) -> BuildResult:
    tag = tag or make_tag(info)
    with staged_context(info) as ctx, tempfile.TemporaryDirectory(prefix="dockhealer-df-") as dfdir:
        dockerfile_path = Path(dfdir) / "Dockerfile"   # named "Dockerfile" so BuildKit errors say "Dockerfile:5"
        dockerfile_path.write_text(dockerfile)
        cmd = ["docker", "build", "--progress=plain", "--label", "dockhealer=1",
               "--tag", tag, "-f", str(dockerfile_path), str(ctx)]
        start = clock()
        try:
            p = runner(cmd, capture_output=True, text=True, errors="replace", timeout=timeout_s)
        except FileNotFoundError as e:
            raise DockerUnavailable("docker CLI not found on PATH") from e
        except subprocess.TimeoutExpired as e:
            log = _text(e.stderr) + _text(e.stdout)
            return BuildResult(False, None, clock() - start, _tail(log), tag, timed_out=True)
        duration = clock() - start
        log = _tail(_text(p.stderr) + _text(p.stdout))
        if p.returncode != 0:
            return BuildResult(False, p.returncode, duration, log, tag)
        return BuildResult(True, 0, duration, log, tag, image_size_bytes=image_size(tag, runner))
